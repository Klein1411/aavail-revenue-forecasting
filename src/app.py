"""Dependency-light HTTP API, implemented using Python's standard library."""
from __future__ import annotations
from dataclasses import dataclass
from functools import lru_cache
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler
from pathlib import Path
from urllib.parse import urlparse, parse_qs
import argparse
import json
import os
import re
import joblib
from .logging_service import read_events, write_event
from .model import predict_window
from .train import train_pipeline


@dataclass(frozen=True)
class Config:
    artifacts: Path = Path('artifacts')
    reports: Path = Path('reports')
    input_dir: Path = Path('data/sample')
    log_file: Path = Path('logs/predictions.jsonl')
    admin_token: str = ''
    train_token: str = ''


@lru_cache(maxsize=4)
def _read_bundle(path: str, mtime: int):
    return joblib.load(path)  # Load only artifacts generated by your own training process.


def bundle(config: Config):
    path = config.artifacts / 'model_bundle.joblib'
    if not path.exists():
        raise FileNotFoundError('Model not trained. Run python -m src.train first.')
    return _read_bundle(str(path), path.stat().st_mtime_ns)


def handler_for(config: Config):
    """Factory enables complete isolation of state during integration tests."""
    root = Path(__file__).resolve().parent.parent

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, format, *args):
            return

        def respond(self, status: int, payload: dict | list):
            raw = json.dumps(payload, ensure_ascii=False, default=str).encode('utf-8')
            self.send_response(status)
            self.send_header('Content-Type', 'application/json; charset=utf-8')
            self.send_header('Content-Length', str(len(raw)))
            self.send_header('Access-Control-Allow-Origin', 'http://localhost:8000')
            self.end_headers()
            self.wfile.write(raw)

        def html(self, content: bytes, content_type='text/html; charset=utf-8'):
            self.send_response(200)
            self.send_header('Content-Type', content_type)
            self.send_header('Content-Length', str(len(content)))
            self.end_headers()
            self.wfile.write(content)

        def params(self):
            result = {k: v[-1] for k, v in parse_qs(urlparse(self.path).query).items()}
            if self.command == 'POST':
                try:
                    length = int(self.headers.get('Content-Length', '0'))
                    if not 0 <= length <= 65536:
                        raise ValueError('Request body exceeds 64KiB')
                    if length:
                        obj = json.loads(self.rfile.read(length).decode('utf-8'))
                        if not isinstance(obj, dict):
                            raise ValueError('JSON payload must be an object')
                        result.update(obj)
                except (ValueError, UnicodeError, json.JSONDecodeError) as exc:
                    raise ValueError(f'Invalid JSON body: {exc}') from exc
            return result

        def is_authorized(self, token):
            return bool(token) and self.headers.get('Authorization') == f'Bearer {token}'

        def do_GET(self):
            try:
                path = urlparse(self.path).path
                if path == '/':
                    return self.html((root / 'assets' / 'index.html').read_bytes())
                if path.startswith('/charts/'):
                    name = path.partition('/charts/')[2]
                    if name in {'eda_daily_revenue.png', 'eda_country_revenue.png', 'model_vs_baseline.png'}:
                        chart = config.reports / name
                        if chart.is_file():
                            return self.html(chart.read_bytes(), 'image/png')
                    return self.respond(404, {'error': 'chart unavailable'})
                if path == '/health':
                    ready = (config.artifacts / 'model_bundle.joblib').exists()
                    return self.respond(200 if ready else 503, {'status': 'ok' if ready else 'model_missing'})
                if path == '/countries':
                    return self.respond(200, {'countries': sorted(bundle(config)['histories'])})
                if path == '/metrics':
                    item = bundle(config)
                    return self.respond(200, {'model': item['model_name'], 'metrics': item['metrics'],
                                              'holdout_days': item['holdout_days'],
                                              'data_mode': item['data_mode']})
                if path == '/logs':
                    if not self.is_authorized(config.admin_token):
                        return self.respond(403, {'error': 'Admin token required'})
                    limit = int(self.params().get('limit', '100'))
                    return self.respond(200, {'events': read_events(config.log_file, limit)})
                return self.respond(404, {'error': 'Not found'})
            except (FileNotFoundError, ValueError) as exc:
                return self.respond(400, {'error': str(exc)})
            except Exception:
                return self.respond(500, {'error': 'Internal server error'})

        def do_POST(self):
            try:
                path = urlparse(self.path).path
                if path == '/predict':
                    params = self.params()
                    date = params.get('date')
                    if date is not None and (not isinstance(date, str) or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', date)):
                        raise ValueError('date must be YYYY-MM-DD')
                    try:
                        duration = int(params.get('duration', 30))
                    except (TypeError, ValueError):
                        raise ValueError('duration must be an integer') from None
                    result = predict_window(bundle(config), params.get('country'), date, duration)
                    write_event(config.log_file, {'event': 'prediction',
                                                  **{key: result[key] for key in ('country', 'date', 'duration_days', 'predicted_revenue', 'model')}})
                    return self.respond(200, result)
                if path == '/train':
                    if not self.is_authorized(config.train_token):
                        return self.respond(403, {'error': 'Train token required'})
                    result = train_pipeline(config.input_dir, config.artifacts, config.reports)
                    _read_bundle.cache_clear()
                    return self.respond(200, {'status': 'trained', 'model': result['model_name']})
                return self.respond(404, {'error': 'Not found'})
            except KeyError as exc:
                return self.respond(404, {'error': str(exc)})
            except FileNotFoundError as exc:
                return self.respond(503, {'error': str(exc)})
            except (ValueError, TypeError) as exc:
                return self.respond(400, {'error': str(exc)})
            except Exception:
                return self.respond(500, {'error': 'Internal server error'})

    return Handler


def create_server(config: Config | None = None, host='127.0.0.1', port=8000):
    return ThreadingHTTPServer((host, port), handler_for(config or Config()))


def main():
    parser = argparse.ArgumentParser(description='AAVAIL revenue forecasting API')
    parser.add_argument('--host', default=os.getenv('HOST', '127.0.0.1'))
    parser.add_argument('--port', type=int, default=int(os.getenv('PORT', '8000')))
    args = parser.parse_args()
    conf = Config(artifacts=Path(os.getenv('ARTIFACTS_DIR', 'artifacts')),
                  reports=Path(os.getenv('REPORTS_DIR', 'reports')),
                  input_dir=Path(os.getenv('INPUT_DIR', 'data/sample')),
                  log_file=Path(os.getenv('LOG_FILE', 'logs/predictions.jsonl')),
                  admin_token=os.getenv('ADMIN_TOKEN', ''),
                  train_token=os.getenv('TRAIN_TOKEN', ''))
    server = create_server(conf, args.host, args.port)
    print(f'Listening at http://{args.host}:{args.port} (Ctrl+C to stop)', flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == '__main__':
    main()
